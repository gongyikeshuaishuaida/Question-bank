def note_text(section: int, number: int, question: Question) -> str:
    prefix = f"202607-暑假-高三-e网通{section}"
    qid = f"{prefix}-{number:02d}"
    paper_name = f"{prefix}.pdf"
    topic_lines = "\n".join(f"  - {topic}" for topic in question.topics)
    tag_lines = "\n".join(f"  - 知识点/{topic}" for topic in question.topics)
    image_status = "已通过" if question.images else "无图片"
    image_embeds = "\n\n".join(
        f"![[attachments/{image}]]" for image in question.images
    )
    body = question.body.strip()
    if image_embeds and "![[attachments/" not in body:
        body = f"{body}\n\n{image_embeds}"
    q_type = "选择题" if number <= 12 else "填空题"
    difficulty = "简单" if number <= 6 else "中等" if number <= 12 else "困难"
    return f"""---
id: {qid}
题型: {q_type}
来源: "[[试卷/{paper_name}|{paper_name}]]"
试卷: {paper_name}
年级: 高三
题号: "{number:02d}"
难度: {difficulty}
水平: 选考
知识点:
{topic_lines}
完成次数: 0
补课:
正确率:
错题原因:
创建日期: {TODAY}
图片核验: {image_status}
tags:
{tag_lines}
---

# 题目 {number:02d}

{body}

---

## 答案

**正确答案：** {question.answer}

---

## 解析

{question.analysis}

---

## 相关链接

- 来源：[[试卷/{paper_name}|{paper_name}]]
"""


def append_review(section: int, generated: list[tuple[int, Path, Question]], reset: bool) -> None:
    image_path = ROOT / "图片核验.md"
    question_path = ROOT / "题目核验.md"
    if reset:
        image_path.write_text(
            "---\ntitle: 图片核验\ndescription: 当前连续处理轮次的题目图片集中核验页\n---\n\n"
            "# 图片核验\n\n",
            encoding="utf-8",
            newline="\n",
        )
        question_path.write_text(
            "---\ntitle: 题目核验\ndescription: 当前连续处理轮次的题目 md 集中核验页\n---\n\n"
            "# 题目核验\n\n",
            encoding="utf-8",
            newline="\n",
        )

    prefix = f"202607-暑假-高三-e网通{section}"
    image_lines = [f"## {prefix}", ""]
    image_count = 0
    for number, path, question in generated:
        if not question.images:
            continue
        rel = path.relative_to(ROOT).with_suffix("").as_posix()
        image_lines.extend([f"### [[{rel}]]", "", "图片核验：已通过", ""])
        for image in question.images:
            image_lines.extend([f"![[attachments/{image}]]", ""])
            image_count += 1
    if image_count == 0:
        image_lines.extend(["本试卷无题内图片。", ""])
    with image_path.open("a", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(image_lines).rstrip() + "\n\n")

    question_lines = [
        f"## {prefix}",
        "",
        "| 题号 | 题型 | 知识点 | 题目 md |",
        "|---|---|---|---|",
    ]
    for number, path, question in generated:
        rel = path.relative_to(ROOT).with_suffix("").as_posix()
        q_type = "选择题" if number <= 12 else "填空题"
        question_lines.append(
            f"| {number:02d} | {q_type} | {question.folder} | [[{rel}]] |"
        )
    with question_path.open("a", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(question_lines).rstrip() + "\n\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("section", type=int, choices=range(1, 7))
    parser.add_argument("--reset-review", action="store_true")
    args = parser.parse_args()

    questions = PAPERS.get(args.section)
    if questions is None:
        raise SystemExit(f"Section {args.section} data has not been added yet.")

    prefix = f"202607-暑假-高三-e网通{args.section}"
    paper_path = ROOT / "试卷" / f"{prefix}.pdf"
    answer_path = ROOT / "试卷" / f"{prefix}-答案.pdf"
    if not paper_path.exists() or not answer_path.exists():
        raise FileNotFoundError(f"Missing paper or answer PDF for {prefix}")

    existing = [
        path
        for path in ROOT.rglob(f"{prefix}-*.md")
        if "_mineru_output" not in path.parts
    ]
    if existing:
        raise FileExistsError(
            "Refusing to overwrite existing notes:\n" + "\n".join(map(str, existing))
        )

    generated: list[tuple[int, Path, Question]] = []
    for number in range(1, 16):
        question = questions[number]
        folder = ROOT / question.folder
        folder.mkdir(exist_ok=True)
        path = folder / f"{prefix}-{number:02d}.md"
        path.write_text(
            note_text(args.section, number, question),
            encoding="utf-8",
            newline="\n",
        )
        generated.append((number, path, question))

    append_review(args.section, generated, args.reset_review)
    print(f"generated notes: {len(generated)}")
    print(f"image embeds: {sum(len(item[2].images) for item in generated)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
