def answer_analysis(answer: str, q_type: str, paper_prefix: str = "", q: int = 0) -> str:
    manual = MANUAL_ANALYSES.get(paper_prefix, {}).get(q)
    if manual:
        return manual
    if "答案卷" in answer:
        return "本题答案按随卷答案页对应题号记录。核验时应同步查看原答案页，确认 OCR 后的评分点没有遗漏。"
    if q_type == "选择题":
        return "本题依据原卷参考答案确定。复习时重点核对题干中的关键概念、限制条件和选项表述。"
    return "根据参考答案中的评分点填写。程序题复习时应重点跟踪变量含义、循环边界和空位所在语句的上下文。"


