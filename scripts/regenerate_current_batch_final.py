def page_blocks(text: str) -> dict[int, str]:
    matches = list(re.finditer(r"===== PAGE (\d+) =====", text))
    if not matches:
        return {1: text}
    pages: dict[int, str] = {}
    for i, m in enumerate(matches):
        n = int(m.group(1))
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        pages[n] = text[start:end].strip()
    return pages


