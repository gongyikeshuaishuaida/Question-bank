def split_questions(text: str, max_q: int) -> tuple[str, dict[int, str]]:
    text = normalize_text(text)
    section_start_candidates = [
        text.find("阅读下列材料"),
        text.find("阅读以下材料"),
        text.find("阅读下列"),
        text.find("阅读以下"),
    ]
    section_start_candidates = [i for i in section_start_candidates if i != -1]
    if section_start_candidates:
        text = text[min(section_start_candidates):]
    markers = []
    for m in re.finditer(r"(?m)^\s*(\d{1,2})[\.．、。]\s*", text):
        n = int(m.group(1))
        if 1 <= n <= max_q:
            markers.append((n, m.start()))
    # OCR sometimes loses line breaks. Add conservative inline starts for missing questions.
    seen = {n for n, _ in markers}
    if len(seen) < max_q:
        for m in re.finditer(r"(?<!\d)(\d{1,2})[\.．、。](?=\S)", text):
            n = int(m.group(1))
            if 1 <= n <= max_q:
                markers.append((n, m.start()))
        # Some OCR output drops the punctuation after a major question number,
        # for example "13 某系统..." or "15 为准备...".
        for m in re.finditer(r"(?<!第)(?<!\d)(1[0-5])\s+(?=[\u4e00-\u9fffA-Za-z])", text):
            n = int(m.group(1))
            if 1 <= n <= max_q:
                markers.append((n, m.start()))
    markers = sorted(set(markers), key=lambda x: x[1])
    first = next((pos for n, pos in markers if n == 1), 0)
    preface = text[:first].strip()
    result: dict[int, str] = {}
    for idx, (n, pos) in enumerate(markers):
        if n in result:
            continue
        end = markers[idx + 1][1] if idx + 1 < len(markers) else len(text)
        if n <= max_q:
            result[n] = text[pos:end].strip()
    return preface, result


