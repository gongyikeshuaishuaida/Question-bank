def is_code_line(line: str) -> bool:
    s = line.strip()
    if not s:
        return False
    if s.startswith(("A.", "B.", "C.", "D.", "- A.", "- B.", "- C.", "- D.", "①", "②", "③")):
        return False
    low = s.lower()
    if s in {"else:", "break", "continue"} or low.startswith(("def ", "def'", "import ", "from ", "for ", "while ", "if ", "elif ", "else:", "return", "leturn", "print", "plt.", "matplotlib.", "pd.")):
        return True
    if re.match(r"^def[A-Za-z_]", s) or re.match(r"^(for|while|if|elif)[A-Za-z_(]", low):
        return True
    if s.startswith(("'''", '"""')):
        return True
    if re.match(r"^[A-Za-z_][A-Za-z0-9_\[\],\-\+\s]*(\.[A-Za-z_][A-Za-z0-9_]*)?\s*[+\-*/]?=", s):
        return True
    if re.match(r"^[A-Za-z_][A-Za-z0-9_]*\s*=\s*", s):
        return True
    if re.match(r"^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)?\(", s) and s.endswith(")"):
        return True
    if s.startswith("#") and len(s) > 1:
        return True
    return False


def fence_python_blocks(text: str) -> str:
    lines = text.splitlines()
    out: list[str] = []
    i = 0
    while i < len(lines):
        if lines[i].strip().startswith("```"):
            out.append(lines[i])
            i += 1
            while i < len(lines):
                out.append(lines[i])
                if lines[i].strip().startswith("```"):
                    i += 1
                    break
                i += 1
            continue
        if not is_code_line(lines[i]):
            out.append(lines[i])
            i += 1
            continue
        start = i
        group: list[str] = []
        while i < len(lines):
            stripped = lines[i].strip()
            if not stripped:
                group.append(lines[i])
                i += 1
                continue
            if is_code_line(lines[i]) or re.match(r"^[\s]+[A-Za-z_#]", lines[i]):
                group.append(lines[i])
                i += 1
                continue
            break
        nonblank = [x for x in group if x.strip()]
        starts_real_code = bool(nonblank and is_code_line(nonblank[0]))
        if nonblank and starts_real_code:
            while out and out[-1].strip() == "":
                out.pop()
            out.append("")
            out.append("```python")
            out.extend(group)
            out.append("```")
            if i < len(lines) and lines[i].strip():
                out.append("")
        else:
            out.extend(lines[start:i])
    return "\n".join(out)


